CREATE TABLE IF NOT EXISTS risk (
 id VARCHAR(36) PRIMARY KEY, title VARCHAR(160) NOT NULL, category VARCHAR(40) NOT NULL,
 owner VARCHAR(100) NOT NULL, loss DOUBLE PRECISION NOT NULL, delay_days INT NOT NULL,
 urgency DOUBLE PRECISION NOT NULL, complexity DOUBLE PRECISION NOT NULL,
 experience DOUBLE PRECISION NOT NULL, workload DOUBLE PRECISION NOT NULL,
 dependencies INT NOT NULL, volatility DOUBLE PRECISION NOT NULL,
 reliability DOUBLE PRECISION NOT NULL, version INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS app_metadata (name VARCHAR(50) PRIMARY KEY, meta_value VARCHAR(100) NOT NULL);
CREATE TABLE IF NOT EXISTS model_version (
 id VARCHAR(36) PRIMARY KEY, created_at VARCHAR(60) NOT NULL, payload TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS custom_measure (
 id VARCHAR(36) PRIMARY KEY, risk_id VARCHAR(36) NOT NULL REFERENCES risk(id) ON DELETE CASCADE,
 title VARCHAR(160) NOT NULL, cost INT NOT NULL, days INT NOT NULL, reduction DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS decision_snapshot (
 id VARCHAR(36) PRIMARY KEY, title VARCHAR(160) NOT NULL, created_at VARCHAR(60) NOT NULL, payload TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS training_dataset (id INT PRIMARY KEY,payload TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS training_run (
 id VARCHAR(36) PRIMARY KEY,started_at VARCHAR(60) NOT NULL,status VARCHAR(20) NOT NULL,
 fingerprint VARCHAR(64),payload TEXT NOT NULL
);
